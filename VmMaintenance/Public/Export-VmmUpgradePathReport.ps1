function Export-VmmUpgradePathReport {
    <#
    .SYNOPSIS
        Upgrade path report for the manager: per host the current Windows and SQL state, workflow position and
        the next step for SQL or Windows with the exact file and language. Writes UpgradePath_<date>.txt (paste
        into the e-mail) and UpgradePath_<date>.csv (one row per step) to Reports\UpgradePath.
    .DESCRIPTION
        Built from the last snapshot of every host (Extractor results included); nothing on a host is read or
        changed. Plaintext by design (host names, never credentials). The tool does not send e-mail: you send it.
        -Clipboard copies the text as well.
    .EXAMPLE
        Export-VmmUpgradePathReport -Open
    .EXAMPLE
        vmm path-report -HostName srv01,srv02
    #>
    [CmdletBinding()]
    param([string[]]$HostName, [switch]$NoBuildList, [switch]$Open, [switch]$Clipboard, [switch]$Quiet)
    $paths = @(Get-VmmUpgradePath -HostName $HostName -NoBuildList:$NoBuildList -PassThru)
    $m = Get-VmmSqlOsMatrix
    $w = Get-VmmTimeWindow
    $stamp = $w.ZoneTime.ToString('yyyy-MM-dd_HHmm')
    $dir = Join-Path (Get-VmmPath -Name Reports) 'UpgradePath'
    if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
    $base = Join-Path $dir "UpgradePath_$stamp"
    $target = "$(Get-VmmSetting 'Policy.TargetOs' -Default '*Server 2019*')".Trim('*').Trim()
    if ($target -notlike 'Windows*') { $target = "Windows $target" }

    $first = { param($p) $f = @($p.Steps | Where-Object Kind -ne 'None')[0]; if ($f) { $f.Kind } else { 'None' } }
    $mgr = Get-VmmSetting 'Reports.ManagerName' -Default ''
    $lines = New-Object System.Collections.Generic.List[string]
    $lines.Add("Subject: Server upgrade programme - next step per server ($($w.ZoneTime.ToString('yyyy-MM-dd')))")
    $lines.Add('')
    $lines.Add("Hello$(if ($mgr) { " $mgr" }),")
    $lines.Add('')
    $lines.Add("Goal: $target on every server. Below, per server: current Windows and SQL Server, where it is in the workflow,")
    $lines.Add('and the next step (SQL service pack first where Windows needs it, then the Windows in-place upgrade in the')
    $lines.Add('server''s own install language, then the latest SQL cumulative update).')
    $lines.Add('')
    $label = @{ Management = 'warn management'; Blocker = 'SQL blocker'; Restart = 'restart'; SqlServicePack = 'SQL service pack'; WindowsUpgrade = 'Windows upgrade'; SqlCumulativeUpdate = 'SQL CU'; Snapshot = 'snapshot needed'; None = 'nothing to do' }
    $byKind = @($paths | ForEach-Object { & $first $_ } | Group-Object | Sort-Object Count -Descending | ForEach-Object { "$($label[$_.Name]): $($_.Count)" })
    $lines.Add("Servers: $($paths.Count) | next step: $($byKind -join ', ')")
    $lines.Add('')
    foreach ($p in $paths) { foreach ($x in (Format-VmmUpgradePath -Path $p)) { $lines.Add($x) }; $lines.Add('') }
    $lines.Add('References:')
    foreach ($s in $m.Sources) { $lines.Add(" - $($s.Name): $($s.Url)") }
    $lines.Add('')
    $lines.Add("Generated by vmm $((Get-Module VmMaintenance).Version) from the last snapshot of each server ($($w.ZoneLabel) $($w.ZoneTime.ToString('yyyy-MM-dd HH:mm'))).")
    $text = $lines -join [Environment]::NewLine
    Set-Content -LiteralPath "$base.txt" -Value $text -Encoding UTF8

    $rows = foreach ($p in $paths) {
        $sql = (@($p.Sql | ForEach-Object { "$($_.Instance) $($_.Product) $($_.Level) $($_.Lang)".Trim() }) -join '; ')
        foreach ($s in $p.Steps) {
            [pscustomobject]@{ Host = $p.Host; Platform = $p.Platform; OS = $p.OS; OsLanguage = $p.OsLang; Policy = $p.Policy; Workflow = $p.Workflow; Sql = $sql
                Step = $s.N; Kind = $s.Kind; Blocking = $s.Blocking; Action = $s.Action; File = $s.File; Language = $s.Lang; Kb = $s.Kb; Reference = $s.Link; Note = $s.Note }
        }
    }
    Export-VmmCsv -InputObject @($rows) -Path "$base.csv"
    if ($Clipboard) { try { Set-Clipboard -Value $text; Write-VmmLog 'Report text copied to the clipboard.' -Level Success } catch { Write-VmmLog "Clipboard not available: $($_.Exception.Message)" -Level Warn } }
    Write-VmmLog "Upgrade path report: $base.txt (paste into the e-mail) and $base.csv" -Level Success
    if ($Open) { try { Start-Process -FilePath "$base.txt" } catch { Write-VmmLog "Could not open the report: $($_.Exception.Message)" -Level Warn } }
    if (-not $Quiet) { [pscustomobject]@{ Text = "$base.txt"; Csv = "$base.csv"; Hosts = $paths.Count } }
}
